################################################################################
# Sample code for Simulation Scenario 3
# Standalone PANR implementation; base R only.
################################################################################

# Settings and true parameters
MC_REPS <- 1000L
N <- 1000L
N_CORES <- 255L
SEED <- 20260914L

TAU_BOUNDS <- rbind(
  tau0 = c(0, 20),
  tau_Z1 = c(-10, 15),
  tau_Z2 = c(-10, 15),
  tau_Z3 = c(-10, 15)
)
colnames(TAU_BOUNDS) <- c("lower", "upper")

PAR <- c(
  "alpha0", "beta0", "beta_Z1", "beta_Z2", "beta_Z3",
  "tau0", "tau_Z1", "tau_Z2", "tau_Z3",
  "eta_Z1", "eta_Z2", "eta_Z3"
)

TRUTH <- c(
  alpha0 = 1,
  beta0 = 0.50, beta_Z1 = 0.30, beta_Z2 = -0.30, beta_Z3 = 0.20,
  tau0 = 10, tau_Z1 = 10, tau_Z2 = -3, tau_Z3 = 2.5,
  eta_Z1 = -0.40, eta_Z2 = 0.80, eta_Z3 = 0.60
)

# ------------------------------------------------------------------------------
# Scenario 3 data generator
# ------------------------------------------------------------------------------

generate_data <- function(n, seed) {
  set.seed(seed)

  # Correlated Bernoulli Z1 and Z2
  p11 <- 0.3 * 0.6 + 0.2 * sqrt(0.3 * 0.7 * 0.6 * 0.4)
  pair <- sample.int(
    4L, n, replace = TRUE,
    prob = c(1 - 0.3 - 0.6 + p11, 0.3 - p11, 0.6 - p11, p11)
  )
  Z1 <- as.numeric(pair %in% c(2L, 4L))
  Z2 <- as.numeric(pair %in% c(3L, 4L))

  # Truncated N(1,1) on (-10,10), generated by inverse CDF
  lo <- pnorm(-10, 1, 1)
  hi <- pnorm(10, 1, 1)
  Z3 <- qnorm(runif(n, lo, hi), 1, 1)
  X <- runif(n, -50, 50)

  slope <- TRUTH["beta0"] + TRUTH["beta_Z1"] * Z1 +
    TRUTH["beta_Z2"] * Z2 + TRUTH["beta_Z3"] * Z3
  tau <- TRUTH["tau0"] + TRUTH["tau_Z1"] * Z1 +
    TRUTH["tau_Z2"] * Z2 + TRUTH["tau_Z3"] * Z3

  Y <- TRUTH["alpha0"] + slope * pmin(X, tau) +
    TRUTH["eta_Z1"] * Z1 + TRUTH["eta_Z2"] * Z2 +
    TRUTH["eta_Z3"] * Z3 + rnorm(n)

  data.frame(Y, X, Z1, Z2, Z3)
}

# ------------------------------------------------------------------------------
# PANR estimator
# ------------------------------------------------------------------------------

profile_fit <- function(dat, tau) {
  Ztau <- cbind(1, dat$Z1, dat$Z2, dat$Z3)
  knot <- as.vector(Ztau %*% tau)
  xmin <- pmin(dat$X, knot)

  Xpsi <- cbind(
    alpha0 = 1,
    beta0 = xmin,
    beta_Z1 = dat$Z1 * xmin,
    beta_Z2 = dat$Z2 * xmin,
    beta_Z3 = dat$Z3 * xmin,
    eta_Z1 = dat$Z1,
    eta_Z2 = dat$Z2,
    eta_Z3 = dat$Z3
  )

  fit <- tryCatch(lm.fit(Xpsi, dat$Y), error = function(e) NULL)
  if (is.null(fit) || fit$rank < ncol(Xpsi) ||
      any(!is.finite(fit$coefficients))) {
    return(list(ok = FALSE, objective = Inf))
  }

  coef <- setNames(as.numeric(fit$coefficients), colnames(Xpsi))
  residual <- dat$Y - as.vector(Xpsi %*% coef)

  list(
    ok = TRUE, coef = coef, residual = residual,
    objective = mean(residual^2),
    Xpsi = Xpsi, Ztau = Ztau, knot = knot
  )
}

H_matrix <- function(dat, pf) {
  slope <- pf$coef["beta0"] + pf$coef["beta_Z1"] * dat$Z1 +
    pf$coef["beta_Z2"] * dat$Z2 + pf$coef["beta_Z3"] * dat$Z3

  Htau <- sweep(
    pf$Ztau, 1L,
    slope * as.numeric(dat$X > pf$knot),
    `*`
  )

  H <- cbind(
    pf$Xpsi[, 1:5, drop = FALSE],
    Htau,
    pf$Xpsi[, 6:8, drop = FALSE]
  )
  colnames(H) <- PAR

  list(H = H, Htau = Htau)
}

initial_tau <- function(dat) {
  d <- nrow(TAU_BOUNDS)
  L <- ceiling(nrow(dat)^(1 / d))
  if (L %% 2L == 0L) L <- L + 1L

  grid <- as.matrix(expand.grid(
    lapply(seq_len(d), function(j)
      seq(TAU_BOUNDS[j, "lower"], TAU_BOUNDS[j, "upper"], length.out = L)),
    KEEP.OUT.ATTRS = FALSE
  ))

  obj <- apply(grid, 1L, function(tau) profile_fit(dat, tau)$objective)
  if (!any(is.finite(obj))) stop("All initialization-grid fits failed.")

  setNames(as.numeric(grid[which.min(obj), ]), rownames(TAU_BOUNDS))
}

panr_step <- function(dat, tau) {
  pf <- profile_fit(dat, tau)
  if (!pf$ok) stop("Profile regression failed.")

  Htau <- H_matrix(dat, pf)$Htau
  score <- colMeans(sweep(Htau, 1L, pf$residual, `*`))
  J <- crossprod(Htau) / nrow(dat)
  rc <- tryCatch(rcond(J), error = function(e) NA_real_)

  # Singular or out-of-bounds updates are rejected; no projection is used.
  if (!is.finite(rc) || rc <= 1e-12) return(tau)

  candidate <- as.numeric(tau) + as.numeric(solve(J, score))
  inside <- all(is.finite(candidate)) &&
    all(candidate >= TAU_BOUNDS[, "lower"]) &&
    all(candidate <= TAU_BOUNDS[, "upper"])

  setNames(if (inside) candidate else as.numeric(tau), rownames(TAU_BOUNDS))
}

fit_panr <- function(dat) {
  tau <- initial_tau(dat)

  # Exactly K_n = ceiling((log n)^2) PANR updates
  for (k in seq_len(ceiling(log(nrow(dat))^2))) {
    tau <- panr_step(dat, tau)
  }

  pf <- profile_fit(dat, tau)
  if (!pf$ok) stop("Final profile regression failed.")

  H <- H_matrix(dat, pf)$H
  n <- nrow(dat)
  A <- crossprod(H) / n
  Omega <- crossprod(H, sweep(H, 1L, pf$residual^2, `*`)) / n
  rc <- tryCatch(rcond(A), error = function(e) NA_real_)
  if (!is.finite(rc) || rc <= 1e-12) stop("Final sandwich matrix is singular.")

  Ainv <- solve(A)
  V <- Ainv %*% Omega %*% t(Ainv) / n
  dimnames(V) <- list(PAR, PAR)

  theta <- c(pf$coef, tau)[PAR]
  list(
    estimate = theta,
    se = setNames(sqrt(pmax(diag(V), 0)), PAR)
  )
}

# ------------------------------------------------------------------------------
# Monte Carlo simulation: print only the manuscript table measures
# ------------------------------------------------------------------------------

one_rep <- function(r) {
  dat <- generate_data(N, SEED + 100000L * N + r)
  fit <- tryCatch(fit_panr(dat), error = function(e) NULL)
  nm <- c(paste0("est.", PAR), paste0("se.", PAR))

  if (is.null(fit)) return(setNames(rep(NA_real_, length(nm)), nm))
  setNames(c(fit$estimate, fit$se), nm)
}

ids <- seq_len(MC_REPS)
if (.Platform$OS.type != "windows" && N_CORES > 1L) {
  res <- parallel::mclapply(
    ids, one_rep,
    mc.cores = min(N_CORES, MC_REPS),
    mc.preschedule = FALSE,
    mc.set.seed = FALSE
  )
} else {
  res <- lapply(ids, one_rep)
}

res <- do.call(rbind, res)
est <- res[, paste0("est.", PAR), drop = FALSE]
se <- res[, paste0("se.", PAR), drop = FALSE]
colnames(est) <- colnames(se) <- PAR
z <- qnorm(0.975)

summarize_one <- function(p) {
  ok <- is.finite(est[, p]) & is.finite(se[, p])
  if (!any(ok)) {
    return(data.frame(
      Parameter = p, Bias = NA, MCSD = NA, RMSE = NA, AVESE = NA, CP = NA
    ))
  }

  e <- est[ok, p]
  s <- se[ok, p]
  truth <- TRUTH[p]

  data.frame(
    Parameter = p,
    Bias = mean(e - truth),
    MCSD = sd(e),
    RMSE = sqrt(mean((e - truth)^2)),
    AVESE = mean(s),
    CP = 100 * mean(e - z * s <= truth & truth <= e + z * s)
  )
}

# Same parameter order used in the manuscript's Scenario 3 panel
order_table <- c(
  "alpha0", "beta0", "tau0", "tau_Z1", "tau_Z2", "tau_Z3",
  "beta_Z1", "beta_Z2", "beta_Z3", "eta_Z1", "eta_Z2", "eta_Z3"
)

summary_table <- do.call(rbind, lapply(order_table, summarize_one))
summary_table[c("Bias", "MCSD", "RMSE", "AVESE")] <-
  lapply(summary_table[c("Bias", "MCSD", "RMSE", "AVESE")], round, 4)
summary_table$CP <- round(summary_table$CP, 1)

print(summary_table, row.names = FALSE)
